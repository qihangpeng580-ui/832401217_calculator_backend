"""src 包 —— 后端源码的根。

------------------------------------------------------------------
各层职责速查
------------------------------------------------------------------

    calculator/   纯计算，不碰数据库、不碰 HTTP，可以单独测试
        tokenizer.py    字符串 → 记号
        parser.py       记号 → 语法树
        evaluator.py    语法树 → 结果

    service/      编排：把"算"和"存"按业务需求组合起来
        calculator_service.py   解析 + 求值 + 格式化
        history_service.py      计算后写库；历史查询与删除

    model/        持久化
        sqlite_store.py         SQLite 的增删查

    controller/   对外接口
        http_controller.py      HTTP 路由、请求解析、响应输出

    common/       跨层共用
        errors.py               统一错误定义（错误码 ↔ HTTP 状态码）

------------------------------------------------------------------
依赖方向（只允许向下）
------------------------------------------------------------------

    controller  →  service  →  calculator
                       ↓
                    model

反向依赖会破坏可测性：如果 calculator 反过来 import 了 model，
它就必须有数据库才能测试，那 157 项单元测试里最快的那 100 多项就跑不动了。

------------------------------------------------------------------
启动方式
------------------------------------------------------------------

    实际启动请用项目根目录的 run.py：

        py -3.12 run.py

    本文件只作为包的说明，不含可执行代码 ——
    这样"入口只有一个"，不会出现"两处都能启动、行为却不一致"的问题。
"""
